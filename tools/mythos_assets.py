"""Shared building blocks for the asset generators of games on this engine.

A game's own generator script imports this and adds its story's models and maps:

    import mythos_assets
    from mythos_assets import Mesh, Grid

  * Mesh   axis-aligned boxes and quads, grouped by material, written as Wavefront OBJ.
  * Grid   a character map you draw rooms on (rect, outline, put) and write as a level file.
  * write_level(dir, name, grid, furniture, title, generator)
  * GENERIC_MODELS   name -> builder for everyday furniture: bed, toilet, shower, fridge,
                     washer, sofa, table, chair, bookshelf, wardrobe, sink, pine.
  * write_models(dir, builders, generator)

Conventions (the same for every game): one map cell = one world unit; world x = column,
z = row, y = up; every model is built around its floor centre with its FRONT facing +z; yaw 0
faces +z (south on the map), 90 faces +x. Material names are texture names (see
src/engine/gfx/materials.h for the ones every game has); "glow_<texture>" draws at full brightness.
"""

import os


class Mesh:
    """Collects axis-aligned quads grouped by material."""

    def __init__(self):
        self.groups = {}  # material -> list of (points, normal)
        self.order = []

    def quad(self, mat, pts, normal, stretch=False):
        if mat not in self.groups:
            self.groups[mat] = []
            self.order.append(mat)
        self.groups[mat].append((pts, normal, stretch))

    def box(self, mat, cx, cy, cz, hx, hy, hz):
        x0, x1 = cx - hx, cx + hx
        y0, y1 = cy - hy, cy + hy
        z0, z1 = cz - hz, cz + hz
        self.quad(mat, [(x1, y0, z0), (x1, y0, z1), (x1, y1, z1), (x1, y1, z0)], (1, 0, 0))
        self.quad(mat, [(x0, y0, z1), (x0, y0, z0), (x0, y1, z0), (x0, y1, z1)], (-1, 0, 0))
        self.quad(mat, [(x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)], (0, 1, 0))
        self.quad(mat, [(x0, y0, z1), (x1, y0, z1), (x1, y0, z0), (x0, y0, z0)], (0, -1, 0))
        self.quad(mat, [(x1, y0, z1), (x0, y0, z1), (x0, y1, z1), (x1, y1, z1)], (0, 0, 1))
        self.quad(mat, [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0)], (0, 0, -1))

    def picture(self, mat, cx, cy, z, hx, hy):
        """A flat image facing +z at depth z, centred on (cx, cy): the whole texture, upright."""
        x0, x1, y0, y1 = cx - hx, cx + hx, cy - hy, cy + hy
        self.quad(mat, [(x0, y0, z), (x1, y0, z), (x1, y1, z), (x0, y1, z)], (0, 0, 1), stretch=True)

    def write(self, path, name, generator="mythos_assets.py"):
        lines = [f"# generated by {generator}", f"o {name}"]
        vert_index = {}
        verts, uvs, norms, faces_by_mat = [], [], [], {}

        for mat in self.order:
            faces = []
            for pts, n, stretch in self.groups[mat]:
                # uv: metres along the two axes of the face (1 texture repeat per unit), or
                # for a picture the whole image once (the OBJ loader flips v, so v = 1 is the
                # top row of the image).
                axis = [i for i in range(3) if n[i] == 0]
                a0, a1 = axis
                lo0 = min(p[a0] for p in pts)
                lo1 = min(p[a1] for p in pts)
                size0 = max(p[a0] for p in pts) - lo0
                size1 = max(p[a1] for p in pts) - lo1
                ids = []
                for p in pts:
                    if stretch:
                        uv = (round((p[a0] - lo0) / size0, 4), round((p[a1] - lo1) / size1, 4))
                    else:
                        uv = (round(p[a0] - lo0, 4), round(p[a1] - lo1, 4))
                    key = (p, uv, n)
                    if key not in vert_index:
                        verts.append(p)
                        uvs.append(uv)
                        norms.append(n)
                        vert_index[key] = len(verts)
                    ids.append(vert_index[key])
                faces.append((ids[0], ids[1], ids[2]))
                faces.append((ids[0], ids[2], ids[3]))
            faces_by_mat[mat] = faces

        for p in verts:
            lines.append(f"v {p[0]:.4f} {p[1]:.4f} {p[2]:.4f}")
        for uv in uvs:
            lines.append(f"vt {uv[0]:.4f} {uv[1]:.4f}")
        for n in norms:
            lines.append(f"vn {n[0]} {n[1]} {n[2]}")
        for mat in self.order:
            lines.append(f"usemtl {mat}")
            for a, b, c in faces_by_mat[mat]:
                lines.append(f"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}")
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")


