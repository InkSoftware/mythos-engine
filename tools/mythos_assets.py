# ---------------------------------------------------------------- levels

class Grid:
    def __init__(self, w, h, fill):
        self.w, self.h = w, h
        self.cells = [[fill] * w for _ in range(h)]

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.cells[y][x] = c

    def outline(self, x0, y0, x1, y1, c):
        for x in range(x0, x1 + 1):
            self.cells[y0][x] = c
            self.cells[y1][x] = c
        for y in range(y0, y1 + 1):
            self.cells[y][x0] = c
            self.cells[y][x1] = c

    def put(self, x, y, c):
        self.cells[y][x] = c

    def rows(self):
        return ["".join(r) for r in self.cells]


def write_level(directory, name, grid, furniture, title, generator, decor=()):
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, name + ".txt")
    lines = [
        f"; {title} zone layout. Generated by {generator}",
        "; [map]: one character per cell. [furniture]: x y model yaw_degrees (solid, one cell each).",
        "[map]",
    ]
    lines += grid.rows()
    lines.append("[furniture]")
    lines += [f"{x} {y} {model} {yaw}" for x, y, model, yaw in furniture]
    if decor:
        # non-solid small objects: (x, y, model, yaw, offX, offZ, lift), offsets in metres from the cell centre
        lines.append("[decor]")
        lines += [f"{x} {y} {model} {yaw} {ox:g} {oz:g} {lift:g}" for x, y, model, yaw, ox, oz, lift in decor]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
