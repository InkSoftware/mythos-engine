def box(m, mat, x0, y0, z0, x1, y1, z1):
    """A box from two corners (Mesh.box takes a centre and half sizes)."""
    m.box(mat, (x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2, abs(x1 - x0) / 2, abs(y1 - y0) / 2, abs(z1 - z0) / 2)


