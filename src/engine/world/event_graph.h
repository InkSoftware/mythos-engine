#ifndef MYTHOS_ENGINE_WORLD_EVENT_GRAPH_H_
#define MYTHOS_ENGINE_WORLD_EVENT_GRAPH_H_

#include <cmath>
#include <utility>
#include <vector>

#include "engine/core/events.h"
#include "engine/world/level.h"
#include "engine/world/trigger.h"

namespace mythos {
// Headless integration for one point subject. Not thread-safe; the owner must
// keep this object alive until an operation and its callbacks have returned.
class EventGraphRuntime {
 public:
  using Flags = EventRuntime::Flags;
  using Callback = EventRuntime::Callback;

  EventGraphRuntime() = default;
  EventGraphRuntime(const EventGraphRuntime&) = delete;
  EventGraphRuntime& operator=(const EventGraphRuntime&) = delete;
  EventGraphRuntime(EventGraphRuntime&&) = delete;
  EventGraphRuntime& operator=(EventGraphRuntime&&) = delete;

  // Atomically replaces triggers and rules, resetting subject/once state.
  // Invalid or duplicate entries and out-of-bounds cell triggers are rejected
  // without changing the existing graph. The level is not retained or watched.
  bool Load(const Level& level) {
    if (busy_) return false;
    const Guard guard(busy_);
    TriggerRuntime triggers;
    EventRuntime rules;
    for (const auto& trigger : level.Triggers()) {
      if ((trigger.shape == TriggerShape::kCell &&
           !level.InBounds(trigger.cell_x, trigger.cell_z)) ||
          !triggers.Add(trigger))
        return false;
    }
    for (const auto& rule : level.Rules())
      if (!rules.Add(rule)) return false;
    triggers_ = std::move(triggers);
    rules_ = std::move(rules);
    return true;
  }

  // Silently re-arms triggers and treats the subject as outside. Rules remain.
  bool Reset() {
    if (busy_) return false;
    triggers_.Reset();
    return true;
  }

  // Silently removes triggers and rules.
  bool Clear() {
    if (busy_) return false;
    triggers_.Clear();
    rules_.Clear();
    return true;
  }

  // Samples once and dispatches hits in ascending trigger ID order. All hits
  // use the same copies of flags and callback, even if callbacks change the
  // caller's arguments. Trigger detail is enter, exit, stay or use. Sampling
  // is discrete; the caller supplies the use-press edge and floor.
  // A non-finite position or empty callback leaves the runtime unchanged.
  // Callback exceptions propagate: the entire sample has already advanced and
  // remaining actions/hits are not dispatched.
  bool Sample(const Vec3& position, const int floor, const bool use_pressed,
              const Flags& flags, const Callback& callback) {
    if (busy_ || !callback || !std::isfinite(position.x) ||
        !std::isfinite(position.y) || !std::isfinite(position.z))
      return false;
    const Guard guard(busy_);
    const Flags snapshot = flags;
    const Callback dispatch = callback;
    const Callback forward = [&dispatch](const EventAction& action) {
      dispatch(action);
    };
    std::vector<TriggerHit> hits;
    if (!triggers_.Update(position, floor, use_pressed, hits)) return false;
    for (const auto& hit : hits) {
      const char* detail = nullptr;
      switch (hit.event) {
        case TriggerEvent::kEnter:
          detail = "enter";
          break;
        case TriggerEvent::kExit:
          detail = "exit";
          break;
        case TriggerEvent::kStay:
          detail = "stay";
          break;
        case TriggerEvent::kUse:
          detail = "use";
          break;
      }
      rules_.Dispatch({EventKind::kTrigger, hit.id, detail, false}, snapshot,
                      forward);
    }
    return true;
  }

  // Explicit dispatch is limited to flag and timer events; trigger events are
  // generated by Sample. Invalid events and empty callbacks have no effect.
  // Flag changes and timers are detected/advanced by the caller, not here.
  bool Dispatch(const Event& event, const Flags& flags,
                const Callback& callback) {
    if (busy_ || !callback || !ValidEvent(event) ||
        (event.kind != EventKind::kFlag && event.kind != EventKind::kTimer))
      return false;
    const Guard guard(busy_);
    const Event event_copy = event;
    const Flags snapshot = flags;
    const Callback dispatch = callback;
    return rules_.Dispatch(event_copy, snapshot, dispatch);
  }

 private:
  // Every public operation rejects reentrancy while a load or dispatch is in
  // progress, including calls made by a callback. Exceptions release the guard.
  struct Guard {
    explicit Guard(bool& busy) : busy_(busy) { busy_ = true; }
    ~Guard() { busy_ = false; }
    bool& busy_;
  };

  TriggerRuntime triggers_;
  EventRuntime rules_;
  bool busy_ = false;
};
}

#endif